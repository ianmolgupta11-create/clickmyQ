CREATE TABLE `PaymentTransaction` (
  `id` VARCHAR(191) NOT NULL,
  `hospitalId` VARCHAR(191) NOT NULL,
  `appointmentId` VARCHAR(191) NULL,
  `billId` VARCHAR(191) NULL,
  `doctorId` VARCHAR(191) NULL,
  `appointmentDate` DATE NULL,
  `timeSlot` VARCHAR(191) NULL,
  `customerId` VARCHAR(191) NULL,
  `idempotencyKey` VARCHAR(191) NULL,
  `cashfreeOrderId` VARCHAR(191) NOT NULL,
  `cfOrderId` VARCHAR(191) NULL,
  `paymentSessionId` TEXT NULL,
  `cashfreePaymentId` VARCHAR(191) NULL,
  `grossAmountPaise` INTEGER NOT NULL,
  `commissionType` VARCHAR(191) NOT NULL DEFAULT 'PERCENTAGE',
  `commissionValue` INTEGER NOT NULL DEFAULT 200,
  `commissionRateBps` INTEGER NOT NULL DEFAULT 200,
  `commissionAmountPaise` INTEGER NOT NULL,
  `vendorAmountPaise` INTEGER NOT NULL,
  `status` VARCHAR(191) NOT NULL DEFAULT 'PENDING',
  `settlementStatus` VARCHAR(191) NOT NULL DEFAULT 'PENDING',
  `paidAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `PaymentTransaction_idempotencyKey_key` (`idempotencyKey`),
  UNIQUE INDEX `PaymentTransaction_cashfreeOrderId_key` (`cashfreeOrderId`),
  INDEX `PaymentTransaction_hospitalId_idx` (`hospitalId`),
  INDEX `PaymentTransaction_appointmentId_idx` (`appointmentId`),
  INDEX `PaymentTransaction_billId_idx` (`billId`),
  INDEX `PaymentTransaction_doctorId_idx` (`doctorId`),
  INDEX `PaymentTransaction_status_idx` (`status`),
  INDEX `PaymentTransaction_settlementStatus_idx` (`settlementStatus`),
  CONSTRAINT `PaymentTransaction_hospitalId_fkey` FOREIGN KEY (`hospitalId`) REFERENCES `Hospital` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `PaymentTransaction_appointmentId_fkey` FOREIGN KEY (`appointmentId`) REFERENCES `Appointment` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `PaymentTransaction_billId_fkey` FOREIGN KEY (`billId`) REFERENCES `Bill` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `PaymentTransaction_doctorId_fkey` FOREIGN KEY (`doctorId`) REFERENCES `Doctor` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `CashfreeWebhookEvent` (
  `id` VARCHAR(191) NOT NULL,
  `eventId` VARCHAR(191) NOT NULL,
  `eventType` VARCHAR(191) NOT NULL,
  `payload` JSON NOT NULL,
  `processed` BOOLEAN NOT NULL DEFAULT false,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `CashfreeWebhookEvent_eventId_key` (`eventId`),
  INDEX `CashfreeWebhookEvent_eventType_idx` (`eventType`),
  INDEX `CashfreeWebhookEvent_processed_idx` (`processed`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
